import Foundation
@main struct CoreTests {
    static func main() throws {
        let root = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("LingMinderTests-\(UUID())")
        defer { try? FileManager.default.removeItem(at:root) }
        var time = Date(timeIntervalSince1970:1_800_000_000)
        let repository = try ItemRepository(url:root.appendingPathComponent("test.sqlite"))
        let core = try TimerCore(repository:repository,now:{time})
        var checks = 0
        func check(_ condition: Bool, _ message: String) { precondition(condition,message); checks += 1; print("PASS \(message)") }
        func rejects(_ text: String) { do { _ = try TimeInput.minutes(text,now:time); fatalError("accepted \(text)") } catch { checks += 1; print("PASS rejects \(text)") } }
        check(try TimeInput.minutes("1",now:time) == 1,"lower boundary")
        check(try TimeInput.minutes("999",now:time) == 999,"upper boundary")
        for bad in ["0","1000","-1","NaN","inf","24:00","12:60","13pm",""] { rejects(bad) }
        var calendar = Calendar(identifier:.gregorian); calendar.timeZone = TimeZone(secondsFromGMT:0)!
        let night = calendar.date(from:DateComponents(year:2026,month:10,day:8,hour:23,minute:55))!
        check(try TimeInput.minutes("00:05",now:night,calendar:calendar) == 10,"clock crosses midnight")
        check(try TimeInput.minutes("12am",now:night,calendar:calendar) == 5,"12h midnight")
        let first = try core.create(kind:.reminder,title:"  ",minutes:1)
        check(first.title.isEmpty,"empty title")
        let second = try core.create(kind:.task,title:"Read",minutes:1)
        time = time.addingTimeInterval(60.1)
        var due = try core.dueItems()
        check(due.count == 2,"simultaneous expiry")
        check(core.items.allSatisfy { $0.state == .due && $0.completedAt == nil },"expiry does not complete")
        try core.markPresented(first.id,revision:first.revision)
        check(try core.dueItems().count == 1,"receipt prevents duplicate")
        let reopened = try TimerCore(repository:repository,now:{time})
        check(try reopened.dueItems().count == 1,"restart persists receipts")
        let snoozed = try core.snooze(first.id,minutes:7)
        check(snoozed.deadline == time.addingTimeInterval(420) && snoozed.revision == 1,"snooze resets deadline and revision")
        try core.markPresented(first.id,revision:0)
        check(core.items.first { $0.id == first.id }!.deliveredRevision == 0,"stale receipt cannot mark new revision")
        let extended = try core.extend(second.id,minutes:5)
        check(extended.deadline == time.addingTimeInterval(300),"extend overdue from now")
        time = time.addingTimeInterval(421)
        due = try core.dueItems(); check(due.count == 2,"snoozed items deliver again")
        _ = try core.finish(first.id)
        check(core.items.first{$0.id == first.id}!.state == .completed,"explicit completion")
        _ = try core.finish(second.id,cancelled:true)
        check(core.active.isEmpty,"cancel removes active")
        let running = try core.create(kind:.task,title:"Keep me",minutes:99)
        try core.bindApple(running.id,identifier:"owned-only")
        try core.clearHistory()
        check(core.items.count == 1 && core.items[0].appleID == "owned-only","clear keeps active and Apple binding")
        time = time.addingTimeInterval(99*60+3600)
        let afterSleep = try TimerCore(repository:repository,now:{time})
        check(try afterSleep.dueItems().count == 1,"wake catches missed deadline")
        try afterSleep.markPresented(running.id,revision:0)
        check(try afterSleep.dueItems().isEmpty,"wake delivery occurs once")
        try core.delete(running.id)
        check(try repository.all().isEmpty,"delete persisted")
        for (start,delta,expected) in [(1,CGFloat(0),1),(1,CGFloat(136),35),(35,CGFloat(-400),1),(1,CGFloat(1000),99),(99,CGFloat(-4),98)] {
            let value = PullValue(start:start,delta:delta)
            check(value.minutes == expected,"drag maps \(start) + \(delta) to \(expected)")
        }
        let dismissing = try core.create(kind:.reminder,title:"Dismiss",minutes:1)
        try core.bindApple(dismissing.id,identifier:"preserved-apple")
        time = time.addingTimeInterval(61)
        _ = try core.dueItems()
        try core.markPresented(dismissing.id,revision:0)
        let ended = try core.dismiss(dismissing.id)
        check(!ended.isActive && ended.state == .dismissed && ended.completedAt == nil,"close ends locally without completion")
        let restart = try TimerCore(repository:repository,now:{time})
        check(try restart.dueItems().isEmpty,"dismissed does not redeliver after restart")
        check(restart.items.first{$0.id == ended.id}?.appleID == "preserved-apple","dismiss preserves Apple binding")
        check(PullValue(start:1,delta:0.1).extensionWidth == 0.1,"first movement has continuous width")
        check(PullValue(start:1,delta:-10).extensionWidth == 0,"pull width cannot shrink below compact origin")
        let canvas = WidgetCanvas()
        canvas.update(603)
        let oldAnimation = canvas.hold(for:355)
        canvas.update(355)
        check(canvas.width == 355 && canvas.drawingWidth == 603,"rebound holds stretched and editor union")
        let newAnimation = canvas.hold(for:680)
        canvas.complete(oldAnimation)
        check(canvas.settlement == newAnimation && canvas.drawingWidth == 680,"stale completion cannot crop new animation")
        canvas.complete(newAnimation)
        check(canvas.drawingWidth == 355 && canvas.settlement == nil,"actual completion releases extra drawing bounds")
        let screen = NSRect(x:100,y:50,width:1200,height:800)
        let logical = NSRect(x:400,y:200,width:355,height:118)
        let normalized = WidgetCanvas.normalizedOrigin(logical,within:screen)
        check(abs(normalized.x*(screen.width-logical.width)+screen.minX-logical.minX)<0.001 && abs(normalized.y*(screen.height-logical.height)+screen.minY-logical.minY)<0.001,"saved visible coordinates round trip without animation padding")
        let edge = WidgetCanvas.clampedOrigin(NSPoint(x:1400,y:900),size:logical.size,within:screen)
        check(edge == NSPoint(x:945,y:732),"visible content stays within screen edges")
        print("\(checks) checks passed")
    }
}
